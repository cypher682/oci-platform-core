#!/usr/bin/env bash
set -euo pipefail

# OCI Object Storage is S3-compatible. Terraform's remote-state backend is
# therefore named "s3" and reads the conventional AWS_* variable names. The
# credentials are OCI Customer Secret Keys and the endpoint is oraclecloud.com.
# No AWS account or resource is involved.
: "${ENV:?ENV is required}"
: "${OCI_NAMESPACE:?OCI_NAMESPACE is required}"
: "${OCI_TFSTATE_BUCKET:?OCI_TFSTATE_BUCKET is required}"
: "${OCI_CLI_REGION:?OCI_CLI_REGION is required}"

TARGET_DIR="${1:-.}"
mkdir -p "$TARGET_DIR"
BACKEND_FILE="${TARGET_DIR}/backend.tf"

cat > "$BACKEND_FILE" <<EOF
# Generated by scripts/ci-backend.sh — do not commit.
terraform {
  backend "s3" {
    bucket   = "${OCI_TFSTATE_BUCKET}"
    key      = "oci-platform-core/${ENV}/terraform.tfstate"
    region   = "us-east-1"
    endpoint = "https://${OCI_NAMESPACE}.compat.objectstorage.${OCI_CLI_REGION}.oraclecloud.com"

    skip_region_validation      = true
    skip_credentials_validation = true
    skip_metadata_api_check     = true
    skip_requesting_account_id  = true
    skip_s3_checksum            = true
    force_path_style            = true
  }
}
EOF

echo "Wrote ${PWD}/${BACKEND_FILE}"
echo "State key: oci-platform-core/${ENV}/terraform.tfstate"
